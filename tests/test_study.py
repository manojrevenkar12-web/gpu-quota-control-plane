import json
from pathlib import Path

import pytest

from gqc import config
from gqc.lab import study
from gqc.sim.evaluate import run_design
from gqc.world.world import build_site

ROOT = Path(__file__).resolve().parents[1]


def test_designs_run_on_a_tiny_site_and_keep_the_books() -> None:
    site = build_site(3, "tiny")
    for name, d in config.designs()["designs"].items():
        m = run_design(site, d["switches"])
        assert 0 < m["gpu_utilisation"] <= 1, name
        assert m["reservations_admitted"] + m["reservations_rejected"] == m["reservations_requested"]
        if d["switches"]["lending"] == "off":
            assert m["lent_node_h"] == 0 and m["sla_short_node_h"] == 0


def test_same_luck_for_every_design() -> None:
    site = build_site(3, "tiny")
    a = run_design(site, config.designs()["designs"]["platform"]["switches"])
    b = run_design(build_site(3, "tiny"), config.designs()["designs"]["platform"]["switches"])
    assert a == b


def test_heldout_runs_once(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.setattr(study, "LOCK", tmp_path / "heldout.lock")
    (tmp_path / "heldout.lock").write_text("{}")
    with pytest.raises(study.HeldOutLocked):
        study.run_heldout_once()


def test_readme_block_is_generated() -> None:
    p = ROOT / "reports" / "dev.json"
    if not p.exists():
        pytest.skip("no report yet")
    res = json.loads(p.read_text())
    readme = (ROOT / "README.md").read_text()
    assert "<!-- results:start -->" in readme and "Generated by `gqc report`" in readme
    assert res["gates"]["platform_pass"]
